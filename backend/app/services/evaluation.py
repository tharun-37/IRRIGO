"""
The evaluation service: serves the artefacts the training and validation runs wrote.

Nothing here recomputes a metric. The reports on disk are the artefacts, and the
dashboard's job is to show them and, importantly, to show their *weak folds*
rather than only their means. A model page that displays a mean R² of 0.71
without the −0.24 underneath it is the single most misleading thing this project
could build.

Every report is read fresh per request. They are a few hundred kilobytes and are
regenerated by long-running scripts, so caching them would mean serving stale
numbers after a retrain with no way to tell.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger("iic.evaluation")


class EvaluationService:
    def __init__(self, reports_dir: Path, models_dir: Path) -> None:
        self.reports_dir = Path(reports_dir)
        self.models_dir = Path(models_dir)

    def _read(self, name: str) -> dict[str, Any] | None:
        path = self.reports_dir / name
        if not path.exists():
            return None
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            logger.exception("report %s is unreadable", path)
            return None

    # --- model performance ------------------------------------------------

    def evaluation(self) -> dict[str, Any] | None:
        return self._read("evaluation.json")

    def model_health(self) -> dict[str, Any]:
        """
        A summary built for the dashboard, including what is missing.

        `trained: false` with a `reason` is a valid, useful state: it is what the
        page shows when `train_model.py` has not been run yet, and it is far more
        useful than an empty page.
        """
        report = self.evaluation()
        model_path = self.models_dir / "nir_model.joblib"
        if report is None:
            return {
                "trained": False,
                "modelPresent": model_path.exists(),
                "reason": (
                    "reports/evaluation.json is missing. Run scripts/train_model.py "
                    "to fit the model and write the evaluation."
                ),
            }

        protocol = report.get("protocol", {})
        grouped = protocol.get("grouped", {})
        station = protocol.get("leave_one_station_out_summary", {})
        crop = protocol.get("leave_one_crop_out_summary", {})
        final = report.get("final_model", {})
        conformal = final.get("conformal", {})

        return {
            "trained": True,
            "modelPresent": model_path.exists(),
            "nRows": report.get("n_rows"),
            "corpusPath": report.get("corpus"),
            "grouped": {
                "maeMm": grouped.get("mae_mm"),
                "r2": grouped.get("r2"),
                "medianAeMm": grouped.get("median_ae_mm"),
                "rmseMm": grouped.get("rmse_mm"),
                "n": grouped.get("n"),
                "within10MmPct": grouped.get("within_10mm_pct"),
            },
            "skillVsPhysics": grouped.get("skill_vs_physics"),
            "trigger": grouped.get("trigger"),
            "leaveOneStationOut": {
                "meanR2": station.get("mean_r2"),
                "minR2": station.get("worst_fold_r2"),
                "worstFold": station.get("worst_fold"),
                "folds": station.get("folds"),
                "negativeFolds": station.get("negative_r2_folds"),
                "all": [
                    {
                        "heldOut": fold.get("held_out"),
                        "r2": fold.get("r2"),
                        "maeMm": fold.get("mae_mm"),
                        "n": fold.get("n"),
                    }
                    for fold in protocol.get("leave_one_station_out", [])
                ],
            },
            "leaveOneCropOut": {
                "meanR2": crop.get("mean_r2"),
                "minR2": crop.get("worst_fold_r2"),
                "worstFold": crop.get("worst_fold"),
                "folds": crop.get("folds"),
                "all": [
                    {
                        "heldOut": fold.get("held_out"),
                        "r2": fold.get("r2"),
                        "maeMm": fold.get("mae_mm"),
                    }
                    for fold in protocol.get("leave_one_crop_out", [])
                ],
            },
            "conformal": [
                {
                    "level": level,
                    "widthMm": values.get("quantile_mm"),
                    "realisedCoverage": values.get("realised_coverage"),
                    "nCalibration": values.get("n_calibration"),
                }
                for level, values in conformal.items()
            ],
            "importance": [
                {"feature": name, "deltaR2": value}
                for name, value in (report.get("importance") or {}).items()
            ],
        }

    # --- external validation ---------------------------------------------

    def external_validation(self) -> dict[str, Any] | None:
        return self._read("external_validation.json")

    def soil_validation(self) -> dict[str, Any] | None:
        return self._read("soil_validation.json")

    def comparison(self) -> dict[str, Any] | None:
        return self._read("v1_vs_v2.json")

    def describe(self) -> dict[str, Any]:
        """Which reports exist, so the dashboard can say what is missing."""
        names = {
            "evaluation": "evaluation.json",
            "externalValidation": "external_validation.json",
            "soilValidation": "soil_validation.json",
            "comparison": "v1_vs_v2.json",
        }
        return {
            "reports": {
                key: (self.reports_dir / filename).exists()
                for key, filename in names.items()
            },
            "modelPresent": (self.models_dir / "nir_model.joblib").exists(),
        }
